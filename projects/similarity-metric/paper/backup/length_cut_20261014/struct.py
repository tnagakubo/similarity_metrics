import re, sys
src, dst = sys.argv[1], sys.argv[2]
t = open(src, encoding="utf8").read()

def block(t, label):
    """return (start, end) of the table float containing \\label{label}"""
    i = t.index("\\label{" + label + "}")
    s = t.rfind("\\begin{table}", 0, i)
    e = t.index("\\end{table}", i) + len("\\end{table}")
    return s, e

# 1. coverage and precision floats removed (with the blank line before each)
for lab in ("tab:coverage", "tab:precision"):
    s, e = block(t, lab)
    pre = t.rfind("\n\n", 0, s)
    t = t[:pre] + t[e:]

# 2. the bias float becomes the merged float
s, e = block(t, "tab:bias")
merged = r"""\begin{table}[ht]
\centering
\caption{Bias, coverage of the 95\% percentile bootstrap confidence interval, RMSE and mean CI width of $\widehat{W}_1$ by scenario and sample size, in the original units of the effect modifier.\label{tab:estimation}}
\input{generated/tab_estimation}%  GENERATED by R/make_paper_tables.R from results/w1_raw_summary.csv (complete tabular)
\begin{tablenotes}
\item Bias is $\text{Mean}(\widehat{W}_1) - W_1$ and RMSE is $\sqrt{\text{Mean}[(\widehat{W}_1 - W_1)^2]}$; coverage is the proportion of the 95\% percentile bootstrap intervals that contain $W_1$, and is zero under S1 because $W_1 = 0$ lies at the parameter space boundary and a percentile interval cannot contain it; CI width is the mean of (upper $-$ lower). Scenarios are specified with $\sigma = 10$. Results based on 10{,}000 replications with $B = 2{,}000$ bootstrap resamples.
\end{tablenotes}
\end{table}"""
t = t[:s] + merged + t[e:]

# 3. every reference to the three retired tables
n0 = len(re.findall(r"tab:(bias|coverage|precision)\}", t))
t = re.sub(r"\\ref\{tab:(bias|coverage|precision)\}", r"\\ref{tab:estimation}", t)
print("refs repointed:", n0)

# 4. references to the (deleted) bounds paragraph of Section 4.4 -> Section 2.4
t = t.replace(r"a sponsor-specified upper bound (Section~\ref{sec:app_clinical})", r"a sponsor-specified upper bound (Section~\ref{sec:inference})")
t = t.replace(r"The illustrative bounds of Section~\ref{sec:app_clinical} are", r"The illustrative bounds of Section~\ref{sec:inference} are")

# 5. Appendix A.3: the text moved from Section 2.2
a = t.index(r"\bmsubsection{Comparison with the Kolmogorov--Smirnov Bound\label{app:ks_bound}}")
t = t.replace(r"\bmsubsection{Comparison with the Kolmogorov--Smirnov Bound\label{app:ks_bound}}",
              r"\bmsubsection{Comparison with the Kolmogorov--Smirnov Bound; Attainment on the Outcome Scale\label{app:ks_bound}}")
anchor = r"is the smallest slope at which a CATE restricted only by its slope produces the margin."
i = t.index(anchor, a) + len(anchor)
add = r"""

% Moved from Section 2.2 on 2026-10-14 (D-20261014-1, needs Tak's veto), verbatim: the sharpness of the Kolmogorov--Smirnov bound within its own class, and the bounded-support / unbounded-support caveat with the Lee et al. comparison.
The Kolmogorov--Smirnov bound is likewise sharp within its own class, by a step CATE of height $\mathrm{TV}(\tau)$ at the point where $|F_1 - F_2|$ is largest. A bound on the magnitude of $\tau$ itself tightens equation~(\ref{eq:heterogeneity_bound}) further: on a support $[a, b]$ the attaining $\tau^*$ ranges over up to $L_{\text{clinical}} (b - a)$, which on the risk-difference scale is \numval{lipRangeAge} for age and \numval{lipRangeSbp} for systolic blood pressure over the recorded supports of Section~\ref{sec:application} (supports that include the records flagged there), exceeding the highest 30-day mortality Lee et al.\ report for any age group (20.5\% above 75 years; Section~\ref{sec:inference}), so that the attaining CATE would require effects far beyond the baseline risks; for distributions with unbounded support no CATE bounded on the outcome scale attains the bound at all."""
t = t[:i] + add + t[i:]
lee_anchor = "attains the bound at all."
j = t.index(lee_anchor, t.index("Moved from Section 2.2 on 2026-10-14")) + len(lee_anchor)
t = t[:j] + r""" The 30-day mortality that Lee et al.\ report for GUSTO-I is 1.1\% below 45 years and 20.5\% above 75 years,\cite{lee1995} a rise of 19.4 percentage points over at least three decades and hence an average prognostic age gradient of at most about $6.5 \times 10^{-3}$ per year (Section~\ref{sec:inference}).""" + t[j:]
k_anchor = "Hence $F_1 = F_2$."
k = t.index(k_anchor, t.index(r"\bmsubsection{Non-negativity")) + len(k_anchor)
t = t[:k] + r"""

% Moved from Section 2.3 on 2026-10-14 (D-20261014-1, needs Tak's veto), verbatim: the pointwise-Jensen derivation of the upward bias of $\widehat{W}_1$.
Upward bias of $\widehat{W}_1$. Since $E\,\hat{F}_r(x) = F_r(x)$, Jensen's inequality gives $E\,|\hat{F}_1(x) - \hat{F}_2(x)| \geq |F_1(x) - F_2(x)|$ at every $x$, and integrating (the integrand is non-negative, so no further condition is needed) $E\,\widehat{W}_1 \geq W_1$ for all $n_1, n_2$.""" + t[k:]
n_anchor = r"\item Under the $t_3$ null the true $W_1$ is zero"
assert t.count(n_anchor) == 1
t = t.replace(n_anchor, r"""\item Cells: E1, unequal regional sizes (100 against 300; 200 against 1{,}000); E2, a $t_3$ reference scaled to SD 10, under the null and under a 5-unit shift; E3, integer-grid data (the S3 contrast rounded to integers at $n = 100$, 200 and 1{,}000); E4, $n = 1{,}000$ per region for the S3 and S5 contrasts; E5 and E6, the application's operating point (the 0.2 SD contrast of S2 at $n = 1{,}000$ per region, and at 2{,}900 against 1{,}200 with both samples rounded to multiples of 10, as systolic blood pressure is recorded).
""" + n_anchor)
open(dst, "w", encoding="utf8").write(t)
print("ok")
