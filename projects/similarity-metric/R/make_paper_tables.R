#!/usr/bin/env Rscript
# make_paper_tables.R — single writer of every data table in the manuscript (Study 2 estimation, Study 1 identification, GUSTO-I application).
# Reads the canonical results CSVs (and data/gusto.csv for the Region 8 baseline table) and writes complete tabular
# environments to paper/generated/tab_*.tex, which the manuscript pulls in with \input{generated/...}. Numbers are generated, never typed (CLAUDE.md Rule 6).
# Deterministic: no RNG. Formatting reproduces the rows that were hand-pasted before 2026-10-11 byte for byte.
# Usage: Rscript projects/similarity-metric/R/make_paper_tables.R   (from the repo root or the project dir)
proj <- if (file.exists("results/w1_raw_summary.csv")) "." else "projects/similarity-metric"
IN  <- file.path(proj, "results", "w1_raw_summary.csv")
OUT <- file.path(proj, "paper", "generated")
dir.create(OUT, showWarnings = FALSE, recursive = TRUE)

d <- read.csv(IN, stringsAsFactors = FALSE)
labels <- c(S1 = "S1 (Null)", S2 = "S2 (0.2$\\sigma$)", S3 = "S3 (0.5$\\sigma$)", S4 = "S4 (1.0$\\sigma$)",
            S5 = "S5 (Scale)", S6 = "S6 (Skew)", S7 = "S7 (Loc+Scale)")
ns <- c(50, 100, 200)
# One rounding rule for the whole lab: decimal round-half-even (scripts/r/numbers_registry.R). formatC/sprintf
# round the binary double and printed 0.9425 as 0.942 on Windows but 0.943 on Linux — see DECISIONS.md D-20261011-2.
root <- tryCatch(system2("git", c("rev-parse", "--show-toplevel"), stdout = TRUE, stderr = FALSE), error = function(e) "../..")
source(file.path(root, "scripts", "r", "numbers_registry.R"))
f  <- function(x, dp) vapply(x, function(v) .num_round_dec(v, dp), "")
fs <- function(x, dp) { s <- f(abs(x), dp); ifelse(x < 0 & as.numeric(s) != 0, paste0("$-", s, "$"), s) }  # signed, math minus
get <- function(s, n, col) d[d$scenario == s & d$n == n, col]

# tab:estimation (2026-10-14, D-20261014-1): the former tab:bias, tab:coverage and tab:precision in one table, 21 rows (S1-S7 x n),
# same precisions as before (True W1 2 dp, bias 3 dp, coverage 3 dp incl. the structural zero of S1, RMSE 2 dp, mean CI width 2 dp).
# The true W1 and the scenario label are printed on the first row of each scenario only.
est_rows <- unlist(lapply(names(labels), function(s) vapply(seq_along(ns), function(j) { n <- ns[j]
  sprintf("%s%s & %s & %d & %s & %s & %s & %s \\\\", if (j == 1 && s != names(labels)[1]) "\\addlinespace\n" else "",
          if (j == 1) labels[[s]] else "", if (j == 1) f(get(s, n, "true_W1"), 2) else "", as.integer(n),
          fs(get(s, n, "bias"), 3), f(get(s, n, "coverage_pct"), 3), f(get(s, n, "rmse"), 2), f(get(s, n, "mean_ci_width"), 2)) }, "")))
stopifnot(length(est_rows) == 21)

hdr <- function(what, src = "results/w1_raw_summary.csv") sprintf("%% GENERATED by R/make_paper_tables.R from %s — %s. Do not edit by hand.", src, what)
H <- function(cols) c(sprintf("\\begin{tabular}{%s}", cols), "\\toprule")
F <- c("\\bottomrule", "\\end{tabular}")
writeLines(c(hdr("tab:estimation (True W1 2 dp; bias 3 dp; coverage 3 dp, S1 = 0.000; RMSE 2 dp; mean CI width 2 dp; 21 rows)"),
             "{\\footnotesize", H("lrrrrrr"),
             "\\textbf{Scenario} & \\textbf{True $W_1$} & $\\boldsymbol{n}$ & \\textbf{Bias} & \\textbf{Coverage} & \\textbf{RMSE} & \\textbf{Mean CI width} \\\\",
             "\\midrule", est_rows, F, "}"), file.path(OUT, "tab_estimation.tex"))
# the three tables above are retired; remove their files so that no stale copy stays in generated/
unlink(file.path(OUT, c("tab_bias.tex", "tab_coverage.tex", "tab_precision.tex")))

# ============================================================================================================
# Study 1 (identification) tables — results/required_n_selection.csv, clustering_sim_summary(_ext).csv
# ============================================================================================================
rn <- read.csv(file.path(proj, "results", "required_n_selection.csv"), stringsAsFactors = FALSE)
cells <- c("Set4_Extremes / sym_severity"   = "Set 4, symmetric severity",
           "Set4_Extremes / sym_prevalence" = "Set 4, symmetric prevalence",
           "Set4_Extremes / asym_severity"  = "Set 4, asymmetric severity",
           "Set4_Extremes / bulk_shift"     = "Set 4, bulk shift (control)",
           "Set3_Mixture / combined"        = "Set 3, combined",
           "Set3_Mixture / shape_skew"      = "Set 3, shape-skewed",
           "Set3_Mixture / shape_sym"       = "Set 3, shape-symmetric")
# Three measures since 2026-09-27 (Tak): RV1-RV3 are not reported (Komiyama et al. introduce one example approach, not an
# evaluated method). The CSV still holds their rows; the table reads W1, KS and SMD only.
# Table 1 (tab:study2_required_n, Sets 3-4, no intervals) was folded into the table below on 2026-10-12 (D-20261012-2, Louis M10).

# Required n with its 95% Monte Carlo interval (W1, KS, SMD): interval columns written by R/required_n.R (delta method on log n).
# All 13 selection cells since 2026-10-11 (D-20261011-11 judgement 2, referee M3): Sets 1-2 first, then the Set 4 / Set 3 cells.
# SMD is blind (status "blind": AUC plateau at chance) or reached in every cell.
# 2026-10-16 (D-20261016-1 Step 2): the "W1 vs KS" separation column dropped — the text no longer compares the two measures'
# required n (efficiency against KS is not an Aim); the counts in results/derived/required_n_separation.csv stay for the repository.
cells_all <- c("Set1_Gaussian / location"  = "Set 1, location",
               "Set1_Gaussian / scale"     = "Set 1, scale",
               "Set1_Gaussian / combined"  = "Set 1, combined",
               "Set2_LogNormal / location" = "Set 2, location",
               "Set2_LogNormal / shape"    = "Set 2, shape",
               "Set2_LogNormal / combined" = "Set 2, combined",
               cells)
GRID_MIN <- 25   # base-grid lower end (results/selection_sim_config.csv column n; NUMBERS_LEDGER.csv row 25)
mc <- rn[rn$threshold == 0.9 & rn$method %in% c("W1", "KS", "SMD"), ]
stopifnot(setequal(names(cells_all), unique(mc$set)), all(table(mc$method) == length(cells_all)), GRID_MIN == min(read.csv(file.path(proj, "results", "selection_sim_config.csv"))$n))
fmtn <- function(x) format(as.integer(x), big.mark = "{,}", trim = TRUE)
# reached at the grid minimum: required_n_lower is NA because the AUC already exceeds the target at n = 25 (no interpolation)
at_floor <- function(r) r$status == "reached" && is.na(r$required_n_lower) && r$required_n == GRID_MIN
cellmc <- function(set, m) { r <- mc[mc$set == set & mc$method == m, ]; stopifnot(nrow(r) == 1)
  if (at_floor(r)) return(sprintf("$\\leq$ %s", fmtn(r$required_n)))
  if (r$status != "reached" || is.na(r$required_n_lower)) return(if (r$status == "reached") fmtn(r$required_n) else r$status)
  sprintf("%s [%s, %s]", fmtn(r$required_n), fmtn(r$required_n_lower), fmtn(r$required_n_upper)) }
# (The separation rule of the two 95% MC intervals, formerly the fifth column, is still counted in R/make_derived_numbers.R ->
#  results/derived/required_n_separation.csv for the repository; it is no longer printed.)
mcrows <- vapply(names(cells_all), function(set) sprintf("%s & %s & %s & %s \\\\", cells_all[[set]], cellmc(set, "W1"), cellmc(set, "KS"), cellmc(set, "SMD")), "")
# The whole tabular is set in \footnotesize (Wiley one-column width): the file opens with "{\footnotesize" and closes with "}".
writeLines(c(hdr("tab:study2_required_n_mc (required n with 95% Monte Carlo interval, W1, KS and SMD, threshold 0.9, all 13 cells; $\\leq$ 25 = reached at the grid minimum; blind = AUC never reaches the target)", "results/required_n_selection.csv"),
             "{\\footnotesize", H("llll"),
             "\\textbf{Cell} & $\\boldsymbol{W_1}$ \\textbf{[95\\% MC interval]} & \\textbf{KS [95\\% MC interval]} & \\textbf{SMD [95\\% MC interval]} \\\\",
             "\\midrule", mcrows, F, "}"), file.path(OUT, "tab_study2_required_n_mc.tex"))

# (tab:study2_ari removed 2026-09-27 with Section 3.1.4: clustering is not reported — PROTOCOL_silhouette_extension.md criterion not met.)

# ============================================================================================================
# Application (GUSTO-I) tables — data/gusto.csv, results/gusto_operability.csv, gusto_r8_w1_per_pair.csv, gusto_lstar_intervals.csv
# ============================================================================================================
g <- read.csv(file.path(proj, "data", "gusto.csv"), stringsAsFactors = FALSE)
r8 <- g[g$regl == 8, ]
skew <- function(x) { m <- mean(x); mean((x - m)^3) / mean((x - m)^2)^1.5 }   # moment skewness (population form)
r8row <- function(label, v) sprintf("%s & %s & %s & %s \\\\", label, f(mean(r8[[v]]), 1), f(sd(r8[[v]]), 1), fs(skew(r8[[v]]), 2))
writeLines(c(hdr("tab:gusto_r8 (Region 8: mean, SD 1 dp; moment skewness 2 dp; regl == 8)", "data/gusto.csv"), H("lccc"),
             "\\textbf{Candidate effect modifier} & \\textbf{Mean} & \\textbf{SD} & \\textbf{Skewness} \\\\",
             "\\midrule", r8row("Age (years)", "age"), r8row("SBP (mmHg)", "sysbp"), F), file.path(OUT, "tab_gusto_r8.tex"))

op <- read.csv(file.path(proj, "results", "gusto_operability.csv"), stringsAsFactors = FALSE)
oprow <- function(label, em) { r <- op[op$em == em, ]
  sprintf("%s & %s--%s & %d / %d \\\\", label, f(min(r$null_q95_anchor), 3), f(max(r$null_q95_anchor), 3), sum(!r$resolved_anchor), nrow(r)) }
writeLines(c(hdr("tab:operability (null 95th percentile range across partners, anchor floor; unresolved = not resolved against the anchor floor)", "results/gusto_operability.csv"), H("lcc"),
             "\\textbf{Candidate effect modifier} & \\textbf{Null 95th pct.} & \\textbf{Unresolved} \\\\",
             "\\midrule", oprow("Age (years)", "age"), oprow("Systolic blood pressure (mmHg)", "sysbp"), F), file.path(OUT, "tab_operability.tex"))

unres <- function(em) op$region[op$em == em & !op$resolved_anchor]

pp <- read.csv(file.path(proj, "results", "gusto_r8_w1_per_pair.csv"), stringsAsFactors = FALSE)
pp <- pp[order(pp$partner), ]
ci <- function(est, lo, hi, dp) sprintf("%s [%s, %s]", f(est, dp), f(lo, dp), f(hi, dp))
# Rank by W1 within each modifier (2026-09-27, Tak: partners are ordered by W1). Distances unresolved against the anchor null
# floor are not ordered among themselves: they share one rank range with a dagger, which must be contiguous (1--6 for age, 1 for SBP).
# 2026-10-16 (D-20261016-1 Step 3): the bracketed 95% patient-level bootstrap rank interval (results/gusto_rank_intervals.csv,
# R/gusto_rank_intervals.R, added 2026-10-11 for referee M4) is no longer printed — the paper delivers distances, not ranks.
# 2026-10-16 (Louis review-fix M6): the Rank columns themselves dropped (a point rank without uncertainty, D-20261011-11 judgement 3);
# the forest plot carries the order with its intervals. Unresolved distances carry the dagger on the W1 cell. The CSV stays in the repository.
dagci <- function(est, lo, hi, em) paste0(ci(est, lo, hi, 2), ifelse(paste0("R", pp$partner) %in% unres(em), "$^\\dagger$", ""))
nabcd <- sprintf("R%d & %d & %s & %s \\\\", pp$partner, pp$n,
                 dagci(pp$W1_age, pp$ci_lower_age, pp$ci_upper_age, "age"),
                 dagci(pp$W1_sysbp, pp$ci_lower_sysbp, pp$ci_upper_sysbp, "sysbp"))
writeLines(c(hdr("tab:gusto_nabcd (W1 and 95% percentile bootstrap CI, 2 dp, by region number; dagger = unresolved against the anchor null floor)", "results/gusto_r8_w1_per_pair.csv + results/gusto_operability.csv"), H("lrll"),
             "\\textbf{Partner} & $n$ & $\\boldsymbol{\\widehat{W}_{1,\\text{age}}}$ \\textbf{(yr) [95\\% CI]} & $\\boldsymbol{\\widehat{W}_{1,\\text{SBP}}}$ \\textbf{(mmHg) [95\\% CI]} \\\\",
             "\\midrule", nabcd, F), file.path(OUT, "tab_gusto_nabcd.tex"))

ls <- read.csv(file.path(proj, "results", "gusto_lstar_intervals.csv"), stringsAsFactors = FALSE)
ls <- ls[order(as.integer(sub("^R", "", ls$partner))), ]
dag <- function(x, partner, em) paste0(f(x, 2), ifelse(partner %in% unres(em), "$^\\dagger$", ""))
lstar <- sprintf("%s & %s & %s & %s & %s \\\\", ls$partner, dag(ls$w1_age, ls$partner, "age"), dag(ls$w1_sbp, ls$partner, "sysbp"),
                 ci(ls$lstar_age, ls$lstar_age_lower, ls$lstar_age_upper, 4), ci(ls$lstar_sbp, ls$lstar_sbp_lower, ls$lstar_sbp_upper, 4))
writeLines(c(hdr("tab:gusto_lstar_joint (W1 2 dp with dagger when unresolved against the anchor floor; L* 4 dp with 95% percentile interval)", "results/gusto_lstar_intervals.csv + results/gusto_operability.csv"), H("lrrrr"),
             "\\textbf{Partner} & $\\boldsymbol{\\widehat{W}_{1,\\text{age}}}$ \\textbf{(yr)} & $\\boldsymbol{\\widehat{W}_{1,\\text{SBP}}}$ \\textbf{(mmHg)} & \\textbf{$L^*$ age (/yr)} & \\textbf{$L^*$ SBP (/mmHg)} \\\\",
             "\\midrule", lstar, F), file.path(OUT, "tab_gusto_lstar_joint.tex"))

# Study 2 interval variants — results/study2_interval_variants.csv (Mike B, 2026-10-12): percentile coverage, upper-limit coverage
# P(W1 <= U) (4 dp: several cells are 0.9999 and must not print as 1.000), basic coverage, mean widths. Rows in CSV order (scenario, n).
iv <- read.csv(file.path(proj, "results", "study2_interval_variants.csv"), stringsAsFactors = FALSE)
stopifnot(nrow(iv) == 21, all(iv$scenario %in% names(labels)))
ivrows <- vapply(seq_len(nrow(iv)), function(i) { r <- iv[i, ]; first <- i == 1 || iv$scenario[i - 1] != r$scenario
  sprintf("%s%s & %d & %s & %s & %s & %s & %s \\\\", if (first && i > 1) "\\addlinespace\n" else "", if (first) labels[[r$scenario]] else "", as.integer(r$n),
          f(r$cov_pct, 3), f(r$cov_upper, 4), f(r$cov_basic, 3), f(r$width_pct, 2), f(r$width_basic, 2)) }, "")
writeLines(c(hdr("tab:study2_intervals (percentile coverage 3 dp, upper-limit coverage P(W1 <= U) 4 dp, basic coverage 3 dp, mean widths 2 dp; 21 rows)", "results/study2_interval_variants.csv"),
             "{\\footnotesize", H("lrrrrrr"),
             "\\textbf{Scenario} & $\\boldsymbol{n}$ & \\textbf{Percentile coverage} & \\textbf{Upper-limit coverage} & \\textbf{Basic coverage} & \\textbf{Mean width (percentile)} & \\textbf{Mean width (basic)} \\\\",
             "\\midrule", ivrows, F, "}"), file.path(OUT, "tab_study2_intervals.tex"))

# Study 2 extension — results/w1_raw_ext_summary.csv (PROTOCOL_study2_extension.md; cells E1a--E6, E3c). Rows in design order (cell id: E1, E2, E3 at n = 100/200/1000, E4, E5, E6),
# labels from the cell id (the CSV group column holds "E5/E6 small distance" for both of the last cells), n1, n2 and Reps in their own columns.
# True W1 2 dp (E6 1.9999999919 prints 2.00), bias 3 dp, RMSE 2 dp, coverage 3 dp, upper-limit coverage 4 dp, mean width 2 dp.
# The Monte Carlo SE of coverage is NOT printed per cell: the note reports its maximum over cells (registry key mcseCovExtMax).
ex <- read.csv(file.path(proj, "results", "w1_raw_ext_summary.csv"), stringsAsFactors = FALSE)
stopifnot(nrow(ex) == 11)
ex_label <- c(E1a = "E1 unequal $n$", E1b = "E1 unequal $n$", E2a = "E2 heavy tails: $t_3$, null", E2b = "E2 heavy tails: $t_3$, shift",
              E3a = "E3 integer grid", E3b = "E3 integer grid", E3c = "E3 integer grid", E4a = "E4 large $n$: S3", E4b = "E4 large $n$: S5",
              E5 = "E5 small distance", E6 = "E6 small distance, unequal $n$, rounded")
ex <- ex[order(ex$cell), ]
exid <- sub("_.*$", "", ex$cell); stopifnot(setequal(exid, names(ex_label)), identical(exid, names(ex_label)))
exrows <- vapply(seq_len(nrow(ex)), function(i) { r <- ex[i, ]
  sprintf("%s & %s & %s & %s & %s & %s & %s & %s & %s & %s \\\\", ex_label[[exid[i]]], fmtn(r$n1), fmtn(r$n2), fmtn(r$n_reps),
          f(r$true_W1, 2), fs(r$bias, 3), f(r$rmse, 2), f(r$coverage, 3), f(r$upper_coverage, 4), f(r$mean_ci_width, 2)) }, "")
writeLines(c(hdr("tab:study2_ext (true W1 2 dp; bias 3 dp; RMSE 2 dp; coverage 3 dp; upper-limit coverage 4 dp; mean width 2 dp; 11 rows in design order)", "results/w1_raw_ext_summary.csv"),
             "{\\footnotesize\\setlength{\\tabcolsep}{4pt}", H("lrrrrrrrrr"),
             "\\textbf{Cell} & $\\boldsymbol{n_1}$ & $\\boldsymbol{n_2}$ & \\textbf{Reps} & \\textbf{True $W_1$} & \\textbf{Bias} & \\textbf{RMSE} & \\textbf{Coverage} & \\textbf{Upper-limit coverage} & \\textbf{Mean width} \\\\",
             "\\midrule", exrows, F, "}"), file.path(OUT, "tab_study2_ext.tex"))

writeLines(capture.output(sessionInfo()), file.path(OUT, "make_paper_tables_sessionInfo.txt"))
cat("make_paper_tables: wrote 8 complete tabulars to", OUT, "\n")
