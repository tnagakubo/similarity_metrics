#!/usr/bin/env Rscript
# make_paper_tables.R — single writer of every data table in the manuscript (Study 2 estimation, Study 1 identification, GUSTO-I application).
# Reads the canonical results CSVs (and data/gusto.csv for the Region 8 baseline table) and writes complete tabular
# environments to paper/generated/tab_*.tex, which the manuscript pulls in with \input{generated/...}. Numbers are generated, never typed (CLAUDE.md Rule 6).
# Deterministic: no RNG. Formatting reproduces the rows that were hand-pasted before 2026-10-11 byte for byte.
# Usage: Rscript projects/similarity-metric/R/make_paper_tables.R   (from the repo root or the project dir)
proj <- if (file.exists("results/w1_raw_summary.csv")) "." else "projects/similarity-metric"
IN  <- file.path(proj, "results", "w1_raw_summary.csv")
OUT <- file.path(proj, "paper", "generated")
dir.create(OUT, showWarnings = FALSE, recursive = TRUE)

d <- read.csv(IN, stringsAsFactors = FALSE)
labels <- c(S1 = "S1 (Null)", S2 = "S2 (0.2$\\sigma$)", S3 = "S3 (0.5$\\sigma$)", S4 = "S4 (1.0$\\sigma$)",
            S5 = "S5 (Scale)", S6 = "S6 (Skew)", S7 = "S7 (Loc+Scale)")
ns <- c(50, 100, 200)
# One rounding rule for the whole lab: decimal round-half-even (scripts/r/numbers_registry.R). formatC/sprintf
# round the binary double and printed 0.9425 as 0.942 on Windows but 0.943 on Linux — see DECISIONS.md D-20261011-2.
root <- tryCatch(system2("git", c("rev-parse", "--show-toplevel"), stdout = TRUE, stderr = FALSE), error = function(e) "../..")
source(file.path(root, "scripts", "r", "numbers_registry.R"))
f  <- function(x, dp) vapply(x, function(v) .num_round_dec(v, dp), "")
fs <- function(x, dp) { s <- f(abs(x), dp); ifelse(x < 0 & as.numeric(s) != 0, paste0("$-", s, "$"), s) }  # signed, math minus
get <- function(s, n, col) d[d$scenario == s & d$n == n, col]

bias <- vapply(names(labels), function(s) sprintf("%s & %s & %s \\\\", labels[s], f(get(s, 50, "true_W1"), 2),
  paste(vapply(ns, function(n) fs(get(s, n, "bias"), 3), ""), collapse = " & ")), "")
cover <- vapply(names(labels)[-1], function(s) sprintf("%s & %s \\\\", labels[s],
  paste(vapply(ns, function(n) f(get(s, n, "coverage_pct"), 3), ""), collapse = " & ")), "")
prec <- vapply(names(labels), function(s) sprintf("%s & %s & %s \\\\", labels[s],
  paste(vapply(ns, function(n) f(get(s, n, "rmse"), 2), ""), collapse = " & "),
  paste(vapply(ns, function(n) f(get(s, n, "mean_ci_width"), 2), ""), collapse = " & ")), "")

hdr <- function(what, src = "results/w1_raw_summary.csv") sprintf("%% GENERATED by R/make_paper_tables.R from %s — %s. Do not edit by hand.", src, what)
H <- function(cols) c(sprintf("\\begin{tabular}{%s}", cols), "\\toprule")
F <- c("\\bottomrule", "\\end{tabular}")
writeLines(c(hdr("tab:bias (True W1 2 dp; bias 3 dp)"), H("lcccc"),
             "\\textbf{Scenario} & \\textbf{True $W_1$} & $\\boldsymbol{n=50}$ & $\\boldsymbol{n=100}$ & $\\boldsymbol{n=200}$ \\\\",
             "\\midrule", bias, F), file.path(OUT, "tab_bias.tex"))
writeLines(c(hdr("tab:coverage (S2-S7, 3 dp)"), H("lccc"),
             "\\textbf{Scenario} & $\\boldsymbol{n=50}$ & $\\boldsymbol{n=100}$ & $\\boldsymbol{n=200}$ \\\\",
             "\\midrule", cover, F), file.path(OUT, "tab_coverage.tex"))
writeLines(c(hdr("tab:precision (RMSE then mean CI width, 2 dp)"), H("lcccccc"),
             "& \\multicolumn{3}{c}{\\textbf{RMSE}} & \\multicolumn{3}{c}{\\textbf{Mean CI Width}} \\\\",
             "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}",
             "\\textbf{Scenario} & $\\boldsymbol{n=50}$ & $\\boldsymbol{n=100}$ & $\\boldsymbol{n=200}$ & $\\boldsymbol{n=50}$ & $\\boldsymbol{n=100}$ & $\\boldsymbol{n=200}$ \\\\",
             "\\midrule", prec, F), file.path(OUT, "tab_precision.tex"))

# ============================================================================================================
# Study 1 (identification) tables — results/required_n_selection.csv, clustering_sim_summary(_ext).csv
# ============================================================================================================
rn <- read.csv(file.path(proj, "results", "required_n_selection.csv"), stringsAsFactors = FALSE)
cells <- c("Set4_Extremes / sym_severity"   = "Set 4, symmetric severity",
           "Set4_Extremes / sym_prevalence" = "Set 4, symmetric prevalence",
           "Set4_Extremes / asym_severity"  = "Set 4, asymmetric severity",
           "Set4_Extremes / bulk_shift"     = "Set 4, bulk shift (control)",
           "Set3_Mixture / combined"        = "Set 3, combined",
           "Set3_Mixture / shape_skew"      = "Set 3, shape-skewed",
           "Set3_Mixture / shape_sym"       = "Set 3, shape-symmetric")
meths <- c("W1", "KS", "SMD", "RV1", "RV2", "RV3")
cell_entry <- function(set, m) {
  r <- rn[rn$set == set & rn$method == m & rn$threshold == 0.9, ]
  stopifnot(nrow(r) == 1)
  if (r$status == "reached") format(as.integer(r$required_n), big.mark = "{,}", trim = TRUE)
  else if (r$status == "blind") "blind"
  else sprintf("partial (%s)", f(r$max_auc, 2))
}
reqn <- vapply(names(cells), function(set) sprintf("%s & %s \\\\", cells[[set]],
  paste(vapply(meths, function(m) cell_entry(set, m), ""), collapse = " & ")), "")
writeLines(c(hdr("tab:study2_required_n (threshold 0.9; reached = n with {,}; blind; partial (max AUC 2 dp))", "results/required_n_selection.csv"), H("lrrllrr"),
             "\\textbf{Cell} & $\\boldsymbol{W_1}$ & \\textbf{KS} & \\textbf{SMD} & \\textbf{RV1} & \\textbf{RV2} & \\textbf{RV3} \\\\",
             "\\midrule", reqn, F), file.path(OUT, "tab_study2_required_n.tex"))

cl  <- read.csv(file.path(proj, "results", "clustering_sim_summary.csv"), stringsAsFactors = FALSE)
clx <- read.csv(file.path(proj, "results", "clustering_sim_summary_ext.csv"), stringsAsFactors = FALSE)
ari <- function(d, set, m, n) { v <- d$value[d$set == set & d$method == m & d$n == n & d$measure == "ari"]; stopifnot(length(v) == 1); v }
sets <- c("Set1_Gaussian", "Set2_LogNormal", "Set3_Mixture", "Set4_Extremes")
mlab <- c(W1 = "$W_1$", KS = "KS", SMD = "SMD", RV1 = "RV1", RV2 = "RV2", RV3 = "RV3")
arirows <- vapply(meths, function(m) sprintf("%s & %s \\\\", mlab[[m]],
  paste(vapply(sets, function(set) sprintf("%s / %s", f(ari(cl, set, m, 100), 3), f(ari(clx, set, m, 2000), 3)), ""), collapse = " & ")), "")
writeLines(c(hdr("tab:study2_ari (ARI at n = 100 / n = 2,000, 3 dp)", "results/clustering_sim_summary.csv + results/clustering_sim_summary_ext.csv"), H("lcccc"),
             "\\textbf{Measure} & \\textbf{Set 1 Gaussian} & \\textbf{Set 2 Log-normal} & \\textbf{Set 3 Mixture} & \\textbf{Set 4 Extremes} \\\\",
             "\\midrule", arirows, F), file.path(OUT, "tab_study2_ari.tex"))

# ============================================================================================================
# Application (GUSTO-I) tables — data/gusto.csv, results/gusto_operability.csv, gusto_r8_w1_per_pair.csv, gusto_lstar_intervals.csv
# ============================================================================================================
g <- read.csv(file.path(proj, "data", "gusto.csv"), stringsAsFactors = FALSE)
r8 <- g[g$regl == 8, ]
skew <- function(x) { m <- mean(x); mean((x - m)^3) / mean((x - m)^2)^1.5 }   # moment skewness (population form)
r8row <- function(label, v) sprintf("%s & %s & %s & %s \\\\", label, f(mean(r8[[v]]), 1), f(sd(r8[[v]]), 1), fs(skew(r8[[v]]), 2))
writeLines(c(hdr("tab:gusto_r8 (Region 8: mean, SD 1 dp; moment skewness 2 dp; regl == 8)", "data/gusto.csv"), H("lccc"),
             "\\textbf{Candidate effect modifier} & \\textbf{Mean} & \\textbf{SD} & \\textbf{Skewness} \\\\",
             "\\midrule", r8row("Age (years)", "age"), r8row("SBP (mmHg)", "sysbp"), F), file.path(OUT, "tab_gusto_r8.tex"))

op <- read.csv(file.path(proj, "results", "gusto_operability.csv"), stringsAsFactors = FALSE)
oprow <- function(label, em) { r <- op[op$em == em, ]
  sprintf("%s & %s--%s & %d / %d \\\\", label, f(min(r$null_q95_anchor), 3), f(max(r$null_q95_anchor), 3), sum(!r$resolved_anchor), nrow(r)) }
writeLines(c(hdr("tab:operability (null 95th percentile range across partners, anchor floor; unresolved = not resolved against the anchor floor)", "results/gusto_operability.csv"), H("lcc"),
             "\\textbf{Candidate effect modifier} & \\textbf{Null 95th pct.} & \\textbf{Unresolved} \\\\",
             "\\midrule", oprow("Age (years)", "age"), oprow("Systolic blood pressure (mmHg)", "sysbp"), F), file.path(OUT, "tab_operability.tex"))

pp <- read.csv(file.path(proj, "results", "gusto_r8_w1_per_pair.csv"), stringsAsFactors = FALSE)
pp <- pp[order(pp$partner), ]
ci <- function(est, lo, hi, dp) sprintf("%s [%s, %s]", f(est, dp), f(lo, dp), f(hi, dp))
nabcd <- sprintf("R%d & %d & %s & %s \\\\", pp$partner, pp$n,
                 ci(pp$W1_age, pp$ci_lower_age, pp$ci_upper_age, 2), ci(pp$W1_sysbp, pp$ci_lower_sysbp, pp$ci_upper_sysbp, 2))
writeLines(c(hdr("tab:gusto_nabcd (W1 and 95% percentile bootstrap CI, 2 dp, by region number)", "results/gusto_r8_w1_per_pair.csv"), H("lrll"),
             "\\textbf{Partner} & $n$ & $\\boldsymbol{\\widehat{W}_{1,\\text{age}}}$ \\textbf{(yr) [95\\% CI]} & $\\boldsymbol{\\widehat{W}_{1,\\text{SBP}}}$ \\textbf{(mmHg) [95\\% CI]} \\\\",
             "\\midrule", nabcd, F), file.path(OUT, "tab_gusto_nabcd.tex"))

ls <- read.csv(file.path(proj, "results", "gusto_lstar_intervals.csv"), stringsAsFactors = FALSE)
ls <- ls[order(as.integer(sub("^R", "", ls$partner))), ]
unres <- function(em) op$region[op$em == em & !op$resolved_anchor]
dag <- function(x, partner, em) paste0(f(x, 2), ifelse(partner %in% unres(em), "$^\\dagger$", ""))
lstar <- sprintf("%s & %s & %s & %s & %s \\\\", ls$partner, dag(ls$w1_age, ls$partner, "age"), dag(ls$w1_sbp, ls$partner, "sysbp"),
                 ci(ls$lstar_age, ls$lstar_age_lower, ls$lstar_age_upper, 4), ci(ls$lstar_sbp, ls$lstar_sbp_lower, ls$lstar_sbp_upper, 4))
writeLines(c(hdr("tab:gusto_lstar_joint (W1 2 dp with dagger when unresolved against the anchor floor; L* 4 dp with 95% percentile interval)", "results/gusto_lstar_intervals.csv + results/gusto_operability.csv"), H("lrrrr"),
             "\\textbf{Partner} & $\\boldsymbol{\\widehat{W}_{1,\\text{age}}}$ \\textbf{(yr)} & $\\boldsymbol{\\widehat{W}_{1,\\text{SBP}}}$ \\textbf{(mmHg)} & \\textbf{$L^*$ age (/yr)} & \\textbf{$L^*$ SBP (/mmHg)} \\\\",
             "\\midrule", lstar, F), file.path(OUT, "tab_gusto_lstar_joint.tex"))

writeLines(capture.output(sessionInfo()), file.path(OUT, "make_paper_tables_sessionInfo.txt"))
cat("make_paper_tables: wrote 9 complete tabulars to", OUT, "\n")
